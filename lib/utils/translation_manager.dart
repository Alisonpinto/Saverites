  // Batch translate from Google Translate API
  static Future<bool> loadLanguage(String languageName) async {
    if (translations.containsKey(languageName) && translations[languageName]!.isNotEmpty) {
      return true;
    }

    final code = languageCodes[languageName];
    if (code == null) return false;

    try {
      final englishMap = translations['English']!;
      final keys = englishMap.keys.toList();

      final Map<String, String> newTranslations = {};
      final List<String> singleSentenceKeys = [];
      final List<String> multiSentenceKeys = [];

      // Helper to check if string contains multiple sentences or newlines
      bool isMultiSentence(String text) {
        if (text.contains('\n')) return true;
        final trimmed = text.trim();
        final firstPeriodIdx = trimmed.indexOf('.');
        if (firstPeriodIdx != -1 && firstPeriodIdx < trimmed.length - 1) {
          return true;
        }
        return false;
      }

      for (final key in keys) {
        final val = englishMap[key]!;
        if (isMultiSentence(val)) {
          multiSentenceKeys.add(key);
        } else {
          singleSentenceKeys.add(key);
        }
      }

      // 1. Translate single-sentence keys in batches of 20 separated by \n
      const int batchSize = 20;
      for (int i = 0; i < singleSentenceKeys.length; i += batchSize) {
        final end = (i + batchSize < singleSentenceKeys.length) ? i + batchSize : singleSentenceKeys.length;
        final batchKeys = singleSentenceKeys.sublist(i, end);
        final batchValues = batchKeys.map((k) => englishMap[k]!).toList();

        try {
          final combinedText = batchValues.join('\n');
          final url = Uri.parse(
            'https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=$code&dt=t&q=${Uri.encodeComponent(combinedText)}'
          );

          final response = await http.get(url).timeout(const Duration(seconds: 4));
          if (response.statusCode == 200) {
            final decoded = jsonDecode(response.body);
            final List sentences = decoded[0] ?? [];
            if (sentences.length == batchKeys.length) {
              for (int j = 0; j < batchKeys.length; j++) {
                final List sentence = sentences[j];
                newTranslations[batchKeys[j]] = (sentence[0]?.toString() ?? '').trim();
              }
            } else {
              // Mismatch fallback: translate these individually
              debugPrint("Batch size mismatch for $languageName ($i-${end-1}): expected ${batchKeys.length}, got ${sentences.length}. Retrying individually.");
              final List<Future<void>> localFutures = [];
              for (int j = 0; j < batchKeys.length; j++) {
                final key = batchKeys[j];
                final value = englishMap[key]!;
                localFutures.add(_translateSingle(value, code).then((translated) {
                  newTranslations[key] = translated;
                }));
              }
              await Future.wait(localFutures);
            }
          }
        } catch (e) {
          debugPrint("Error translating batch ($i-${end-1}): $e");
          // Fallback
          final List<Future<void>> localFutures = [];
          for (int j = 0; j < batchKeys.length; j++) {
            final key = batchKeys[j];
            final value = englishMap[key]!;
            localFutures.add(_translateSingle(value, code).then((translated) {
              newTranslations[key] = translated;
            }));
          }
          await Future.wait(localFutures);
        }

        // Brief delay between sequential batches to respect Google Translate API limits
        await Future.delayed(const Duration(milliseconds: 50));
      }

      // 2. Translate multi-sentence keys in parallel
      if (multiSentenceKeys.isNotEmpty) {
        final List<Future<void>> multiFutures = [];
        for (final key in multiSentenceKeys) {
          final value = englishMap[key]!;
          multiFutures.add(_translateSingle(value, code).then((translated) {
            newTranslations[key] = translated;
          }));
        }
        await Future.wait(multiFutures);
      }

      if (newTranslations.length == keys.length) {
        translations[languageName] = newTranslations;
        return true;
      }
    } catch (e) {
      debugPrint("Error loading language translation for '$languageName': $e");
    }
    return false;
  }

  static Future<String> _translateSingle(String text, String targetCode) async {
    if (text.isEmpty) return '';
    try {
      final url = Uri.parse(
        'https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=$targetCode&dt=t&q=${Uri.encodeComponent(text)}'
      );
      final response = await http.get(url);
      if (response.statusCode == 200) {
        final decoded = jsonDecode(response.body);
        final List sentences = decoded[0] ?? [];
        final buffer = StringBuffer();
        for (var sentence in sentences) {
          if (sentence is List && sentence.isNotEmpty) {
            buffer.write(sentence[0]);
          }
        }
        return buffer.toString().trim();
      }
    } catch (e) {
      debugPrint("Individual key translation error: $e");
    }
    return text;
  }
